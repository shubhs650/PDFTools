// M0-S6: generate docs/plan/S6-icon-map.md (per-command icon map, coverage
// summary, custom list, bundle cost) and out/s6-preview.html (a visual sheet
// of the chosen Fluent glyphs, Regular vs Color, for the owner's review).
//
// Usage: node spikes/s6-icons/bundle.ts && node spikes/s6-icons/icon-map.ts

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createElement, type ComponentType } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import * as Icons from '@fluentui/react-icons';
import { format, resolveConfig } from 'prettier';
import { loadCatalog, resolve, SMALL, type Resolved, type StyleFit } from './catalog.ts';
import { COMMANDS, HOME_REUSES } from './commands.ts';

const here = import.meta.dirname;
const root = join(here, '..', '..');
mkdirSync(join(here, 'out'), { recursive: true });
const cat = loadCatalog();
const rows = COMMANDS.map((c) => resolve(c, cat));
const version = (
  JSON.parse(
    readFileSync(join(root, 'node_modules/@fluentui/react-icons/package.json'), 'utf8'),
  ) as { version: string }
).version;

const cell = (r: Resolved, f: StyleFit): string => {
  if (!f.ok) return f.small ? '20 only' : '—';
  if (r.cmd.size === 'small') return `✓ ${String(SMALL)}`;
  return f.large === 32 ? '✓ 20/32' : `20/${String(f.large)}→32`;
};

// ---- summary -----------------------------------------------------------------------------
const n = rows.length;
const count = (p: (r: Resolved) => boolean): number => rows.filter(p).length;
const large = count((r) => r.cmd.size === 'large');
const summary = {
  commands: n,
  large,
  small: n - large,
  uniqueFluentIcons: new Set(rows.map((r) => r.cmd.fluent)).size,
  custom: count((r) => !!r.cmd.custom),
  colorUsable: count((r) => r.fit.Color.ok),
  colorExact: count((r) => r.fit.Color.exact),
  colorUsableNonCustom: count((r) => r.fit.Color.ok && !r.cmd.custom),
  regularExact: count((r) => r.fit.Regular.exact),
  regularLargeScaled: count(
    (r) => r.cmd.size === 'large' && r.fit.Regular.ok && !r.fit.Regular.exact,
  ),
  regularLargeBy: Object.fromEntries(
    [32, 28, 24].map((s) => [s, count((r) => r.cmd.size === 'large' && r.fit.Regular.large === s)]),
  ),
  filledUsable: count((r) => r.fit.Filled.ok),
};
const bundlePath = join(here, 'out', 's6-bundle.json');
const bundle = existsSync(bundlePath)
  ? (JSON.parse(readFileSync(bundlePath, 'utf8')) as Record<
      string,
      { kB: number; gzipKB: number; brotliKB: number; buildMs: number }
    >)
  : undefined;

// ---- markdown ----------------------------------------------------------------------------
const pct = (x: number): string => `${String(Math.round((x / n) * 100))} %`;
const md: string[] = [
  '# S6 — Ribbon icon map (Fluent UI System Icons)',
  '',
  `> Generated by \`node spikes/s6-icons/icon-map.ts\` from \`spikes/s6-icons/commands.ts\` against`,
  `> \`@fluentui/react-icons\` ${version}. Do not edit by hand. Decision record:`,
  '> [ADR-010](../adr/010-s6-fluent-icons.md).',
  '',
  '## How to read this',
  '',
  '- **Size.** Small buttons, panes and the status bar use the 20 px glyph. Large ribbon buttons',
  '  are 32 px (§8) and use the 32 px glyph, or the largest of 28/24 px scaled up (`24→32`).',
  '- **Color / Regular / Filled.** Whether that style exists at the needed sizes. `—` means none.',
  '- **Custom.** We draw our own icon in `/src/ui/icons` on the Fluent grid. The Fluent icon',
  '  shown is the interim fallback until then.',
  `- Home reuses these commands with the same icons: ${HOME_REUSES.map((h) => `\`${h}\``).join(', ')}.`,
  '',
  '## Summary',
  '',
  '| Measure | Value |',
  '| --- | --- |',
  `| Commands with an icon entry | ${String(n)} (${String(large)} large, ${String(n - large)} small) |`,
  `| Distinct Fluent base icons used | ${String(summary.uniqueFluentIcons)} |`,
  `| Custom icons needed | ${String(summary.custom)} |`,
  `| **Color** style usable | **${String(summary.colorUsable)} (${pct(summary.colorUsable)})**, of which ${String(summary.colorUsableNonCustom)} are not custom |`,
  `| Regular style usable | ${String(n)} (100 %) |`,
  `| Regular at native size (no scaling) | ${String(summary.regularExact)} (${pct(summary.regularExact)}) |`,
  `| Large buttons by native Regular size | 32 px: ${String(summary.regularLargeBy[32])} · 28 px: ${String(summary.regularLargeBy[28])} · 24 px: ${String(summary.regularLargeBy[24])} |`,
  `| Filled style usable | ${String(summary.filledUsable)} (${pct(summary.filledUsable)}) |`,
  '',
];
if (bundle) {
  md.push(
    '## Bundle cost (tree-shaken, minified, React external)',
    '',
    '| Variant | Raw | gzip | brotli | Build |',
    '| --- | --- | --- | --- | --- |',
    ...Object.entries(bundle)
      .filter(([k]) => k !== 'icons')
      .map(
        ([k, v]) =>
          `| ${k} | ${String(v.kB)} kB | ${String(v.gzipKB)} kB | ${String(v.brotliKB)} kB | ${String(v.buildMs)} ms |`,
      ),
    '',
  );
}
for (const tab of [...new Set(rows.map((r) => r.cmd.tab))]) {
  md.push(
    `## ${tab}`,
    '',
    '| Command | Size | Fluent icon | Color | Regular | Filled | Custom |',
    '| --- | --- | --- | --- | --- | --- | --- |',
  );
  for (const r of rows.filter((x) => x.cmd.tab === tab)) {
    const note = r.cmd.custom ? `**Custom:** ${r.cmd.custom}` : (r.cmd.note ?? '');
    md.push(
      `| ${r.cmd.label} <br>\`${r.cmd.id}\` | ${r.cmd.size} | \`${r.cmd.fluent}\` | ${cell(r, r.fit.Color)} | ${cell(r, r.fit.Regular)} | ${cell(r, r.fit.Filled)} | ${note} |`,
    );
  }
  md.push('');
}
md.push('## Custom icon list', '', '| Command | Brief |', '| --- | --- |');
for (const r of rows.filter((x) => x.cmd.custom))
  md.push(`| ${r.cmd.label} (\`${r.cmd.id}\`) | ${r.cmd.custom ?? ''} |`);
md.push('');
const mapPath = join(root, 'docs', 'plan', 'S6-icon-map.md');
writeFileSync(
  mapPath,
  await format(md.join('\n'), { ...(await resolveConfig(mapPath)), parser: 'markdown' }),
);
writeFileSync(
  join(here, 'out', 's6-map.json'),
  JSON.stringify({ version, summary, bundle }, null, 2),
);

// ---- preview sheet (for review only; never shipped) -------------------------------------------
const icons = Icons as unknown as Record<
  string,
  ComponentType<{ 'aria-hidden'?: boolean }> | undefined
>;
const glyph = (name: string): string => {
  const C = icons[name];
  return C
    ? renderToStaticMarkup(createElement(C, { 'aria-hidden': true }))
    : '<span class="x">—</span>';
};
const esc = (s: string): string => s.replace(/&/g, '&amp;').replace(/</g, '&lt;');
const tiles = rows
  .map((r) => {
    const big = r.cmd.size === 'large';
    const regName = big
      ? `${r.cmd.fluent}${String(r.fit.Regular.large)}Regular`
      : `${r.cmd.fluent}20Regular`;
    const colName =
      big && r.fit.Color.large
        ? `${r.cmd.fluent}${String(r.fit.Color.large)}Color`
        : `${r.cmd.fluent}20Color`;
    return `<figure class="${big ? 'big' : ''}${r.cmd.custom ? ' custom' : ''}"><div class="g">${glyph(regName)}${r.fit.Color.ok ? glyph(colName) : ''}</div><figcaption>${esc(r.cmd.label)}<br><code>${r.cmd.fluent}</code></figcaption></figure>`;
  })
  .join('\n');
writeFileSync(
  join(here, 'out', 's6-preview.html'),
  `<!doctype html><html lang="en"><meta charset="utf-8"><title>S6 icon preview</title><style>
body{font:12px system-ui,sans-serif;margin:16px;background:#fff;color:#242424}
h1{font-size:16px}.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(120px,1fr));gap:8px}
figure{margin:0;border:1px solid #e0e0e0;border-radius:4px;padding:6px;text-align:center}
figure.custom{border:2px dashed #c50f1f}.g{display:flex;gap:8px;justify-content:center;align-items:center;height:40px}
.g svg{width:20px;height:20px}.big .g svg{width:32px;height:32px}code{font-size:10px;color:#616161}.x{color:#bbb}
</style><h1>S6 — chosen Fluent glyphs: Regular, then Color where it exists. Dashed red = custom icon needed (Fluent glyph is the interim fallback).</h1>
<div class="grid">${tiles}</div></html>`,
);
console.log(JSON.stringify(summary, null, 1));
