// Generates src/ui/icons/fluent.generated.ts from the command table
// (src/app/commands.ts) and the installed Fluent package (ADR-010 decision 4):
// one per-icon path import per glyph, never the root barrel. A renamed or
// removed Fluent icon then fails typecheck and build.
//
// Usage: node scripts/gen-icons.ts [--check]   (--check: exit 1 if out of date)

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { COMMANDS } from '../src/app/commands.ts';
import { SMALL_SIZE, largeSize, loadCatalog, type IconStyle } from './icon-catalog.ts';

export const OUT = 'src/ui/icons/fluent.generated.ts';

export function generate(): string {
  const cat = loadCatalog();
  const imports = new Map<string, Set<string>>(); // atom → export names
  const need = (atom: string, name: string): string => {
    let s = imports.get(atom);
    if (!s) imports.set(atom, (s = new Set()));
    s.add(name);
    return name;
  };
  const rows: string[] = [];
  const problems: string[] = [];

  for (const c of COMMANDS) {
    const entry = cat.get(c.fluent);
    if (!entry) {
      problems.push(`${c.id}: no Fluent icon "${c.fluent}"`);
      continue;
    }
    const pick = (style: IconStyle): string[] => {
      if (!entry.sizes[style].has(SMALL_SIZE)) {
        problems.push(`${c.id}: ${c.fluent} has no ${String(SMALL_SIZE)} px ${style}`);
        return [];
      }
      const parts = [`small: ${need(entry.atom, `${c.fluent}${String(SMALL_SIZE)}${style}`)}`];
      if (c.size === 'large') {
        const size = largeSize(entry, style);
        if (!size) problems.push(`${c.id}: ${c.fluent} has no large ${style} glyph`);
        else
          parts.push(
            `large: ${need(entry.atom, `${c.fluent}${String(size)}${style}`)}`,
            `largeNative: ${String(size)}`,
          );
      }
      return parts;
    };
    const regular = pick('Regular');
    const filled = c.toggle ? pick('Filled') : null;
    rows.push(
      `  '${c.id}': { regular: { ${regular.join(', ')} }${filled ? `, filled: { ${filled.join(', ')} }` : ''} },`,
    );
  }
  if (problems.length) throw new Error(`Icon registry problems:\n${problems.join('\n')}`);

  const importLines = [...imports.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([atom, names]) =>
        `import { ${[...names].sort().join(', ')} } from '@fluentui/react-icons/svg/${atom}';`,
    );

  return `// GENERATED by scripts/gen-icons.ts from src/app/commands.ts — do not edit.
// Fluent UI System Icons (MIT), per-icon path imports only (ADR-010).
import type { FluentGlyphs } from './types';
${importLines.join('\n')}

export const FLUENT_GLYPHS: Record<string, FluentGlyphs> = {
${rows.join('\n')}
};
`;
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) {
  const text = generate();
  if (process.argv.includes('--check')) {
    if (readFileSync(OUT, 'utf8') !== text) {
      console.error(`${OUT} is out of date: run node scripts/gen-icons.ts`);
      process.exit(1);
    }
    console.log(`${OUT} is up to date`);
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT}`);
  }
}
